DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS meetings;
DROP TABLE IF EXISTS Course;
DROP TABLE IF EXISTS Users;
DROP TABLE IF EXISTS Teacher;
DROP TABLE IF EXISTS Department;
DROP TABLE IF EXISTS Rooms;
DROP TABLE IF EXISTS schools;
DROP TABLE IF EXISTS Address;
DROP TABLE IF EXISTS postal_codes;

CREATE TABLE postal_codes (
    postnr VARCHAR(10) PRIMARY KEY,
    city VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE Address (
    id INT PRIMARY KEY,
    vejnavn VARCHAR(100) NOT NULL,
    husnr VARCHAR(20) NOT NULL,
    postnr VARCHAR(10) NOT NULL,
    CONSTRAINT fk_address_postnr FOREIGN KEY (postnr) REFERENCES postal_codes(postnr)
) ENGINE=InnoDB;

CREATE TABLE schools (
    id INT PRIMARY KEY,
    schoolname VARCHAR(150) NOT NULL,
    address_id INT NULL,
    CONSTRAINT fk_school_address FOREIGN KEY (address_id) REFERENCES Address(id)
) ENGINE=InnoDB;

CREATE TABLE Department (
    id INT PRIMARY KEY,
    departmentname VARCHAR(150) NOT NULL,
    school_id INT NOT NULL,
    CONSTRAINT fk_department_school FOREIGN KEY (school_id) REFERENCES schools(id)
) ENGINE=InnoDB;

CREATE TABLE Rooms (
    id INT PRIMARY KEY,
    room_name VARCHAR(50) NOT NULL,
    building VARCHAR(100) NOT NULL,
    school_id INT NOT NULL,
    CONSTRAINT fk_room_school FOREIGN KEY (school_id) REFERENCES schools(id)
) ENGINE=InnoDB;

CREATE TABLE Teacher (
    id INT PRIMARY KEY,
    firstname VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    department_id INT NOT NULL,
    CONSTRAINT fk_teacher_department FOREIGN KEY (department_id) REFERENCES Department(id)
) ENGINE=InnoDB;

CREATE TABLE Users (
    id INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    tlfnr VARCHAR(30) NOT NULL,
    department_id INT NOT NULL,
    address_id INT NULL,
    CONSTRAINT fk_user_department FOREIGN KEY (department_id) REFERENCES Department(id),
    CONSTRAINT fk_user_address FOREIGN KEY (address_id) REFERENCES Address(id)
) ENGINE=InnoDB;

CREATE TABLE Course (
    id INT PRIMARY KEY,
    coursename VARCHAR(150) NOT NULL,
    teacher_id INT NOT NULL,
    department_id INT NOT NULL,
    room_id INT NOT NULL,
    CONSTRAINT fk_course_teacher FOREIGN KEY (teacher_id) REFERENCES Teacher(id),
    CONSTRAINT fk_course_department FOREIGN KEY (department_id) REFERENCES Department(id),
    CONSTRAINT fk_course_room FOREIGN KEY (room_id) REFERENCES Rooms(id)
) ENGINE=InnoDB;

CREATE TABLE meetings (
    id INT PRIMARY KEY,
    weekdays VARCHAR(30) NOT NULL,
    course_id INT NOT NULL,
    CONSTRAINT fk_meeting_course FOREIGN KEY (course_id) REFERENCES Course(id)
) ENGINE=InnoDB;

CREATE TABLE enrollments (
    id INT PRIMARY KEY,
    user_id INT NOT NULL,
    course_id INT NOT NULL,
    grade VARCHAR(5) NULL,
    CONSTRAINT fk_enrollment_user FOREIGN KEY (user_id) REFERENCES Users(id),
    CONSTRAINT fk_enrollment_course FOREIGN KEY (course_id) REFERENCES Course(id),
    CONSTRAINT uq_user_course UNIQUE (user_id, course_id)
) ENGINE=InnoDB;

