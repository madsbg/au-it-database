-- Session 1: Students + Enrollments (MariaDB)
-- Creates:
--   course.students  (112 rows)
--   course.courses   (10 rows)
--   course.enrollments (282 rows)
-- Designed for basic SELECT/WHERE/ORDER BY and later JOIN/GROUP BY exercises.

CREATE DATABASE IF NOT EXISTS course;
USE course;

-- Drop in dependency order
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS students;

CREATE TABLE students (
  id              INT           NOT NULL AUTO_INCREMENT,
  first_name      VARCHAR(50)   NOT NULL,
  last_name       VARCHAR(50)   NOT NULL,
  email           VARCHAR(120)  NOT NULL,
  birth_year      INT           NULL,
  program         VARCHAR(80)   NOT NULL,
  city            VARCHAR(80)   NOT NULL,
  enrollment_date DATE          NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_students_email (email)
) ENGINE=InnoDB;

CREATE TABLE courses (
  id         INT          NOT NULL AUTO_INCREMENT,
  code       VARCHAR(20)  NOT NULL,
  title      VARCHAR(120) NOT NULL,
  ects       INT          NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_courses_code (code)
) ENGINE=InnoDB;

CREATE TABLE enrollments (
  id          INT          NOT NULL AUTO_INCREMENT,
  student_id  INT          NOT NULL,
  course_id   INT          NOT NULL,
  enrolled_at DATE         NOT NULL,
  status      VARCHAR(20)  NOT NULL,  -- enrolled | completed | dropped
  grade       INT          NULL,      -- only set when completed
  PRIMARY KEY (id),
  KEY ix_enrollments_student (student_id),
  KEY ix_enrollments_course  (course_id),
  CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) REFERENCES students(id),
  CONSTRAINT fk_enrollments_course  FOREIGN KEY (course_id)  REFERENCES courses(id)
) ENGINE=InnoDB;

